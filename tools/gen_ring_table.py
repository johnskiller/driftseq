#!/usr/bin/env python3
"""tools/gen_ring_table.py — generate firmware/src/ring_table.h.

The ARP page places points on a circle. The old code carried a hand-typed
int16 table RING_SIN[64] scaled by 1962, used as

    px = cx + RING_SIN[a]        * r / 1962
    py = cy - RING_SIN[(a+16)&63] * r / 1962

That table is not a 64-step sine. Fitted, its period is ~70.75 steps, not 64,
so pairing a 64-step index with a (a+16) quarter-turn shift does not give a
circle: measured against the origin, T[a]^2 + T[a+16]^2 ranges over
0.81..1.35 of the ideal 1962^2, and the drawn radius wobbles 33%
(0.888r .. 1.182r). Nothing tested it, so it survived from r16j onwards.

This generator replaces it with a pair of Q12 unit vectors per direction:
64 directions, north = slot 0, clockwise. One table serves every n (a track's
euclid length is any 1..64), because a point at index i of n is direction
a = i*64/n. 64*2*2 = 256 bytes, versus 128 bytes for the wrong table.

The 64 directions are exact at the quarters (0,-4096), (4096,0), (0,4096),
(-4096,0) and never more than 0.5 lsb off the unit circle.

Run: python3 tools/gen_ring_table.py   (writes firmware/src/ring_table.h)
"""
import math
import pathlib

N = 64                       # directions
SCALE = 4096                 # Q12
OUT = pathlib.Path(__file__).resolve().parent.parent / "firmware" / "src" / "ring_table.h"


def main() -> int:
    ux = [round(SCALE * math.cos(-math.pi / 2 + a * 2 * math.pi / N)) for a in range(N)]
    uy = [round(SCALE * math.sin(-math.pi / 2 + a * 2 * math.pi / N)) for a in range(N)]

    # the table is only useful if it really is a unit circle and the quarters
    # land exactly; fail the generator rather than ship a table nobody checked
    assert (ux[0], uy[0]) == (0, -SCALE), "slot 0 must be north"
    assert (ux[N // 4], uy[N // 4]) == (SCALE, 0), "slot 16 must be east"
    assert (ux[N // 2], uy[N // 2]) == (0, SCALE), "slot 32 must be south"
    assert (ux[3 * N // 4], uy[3 * N // 4]) == (-SCALE, 0), "slot 48 must be west"
    worst = max(abs(math.hypot(ux[a], uy[a]) - SCALE) for a in range(N))
    assert worst < 1.0, f"radius error {worst:.3f} lsb is too large"

    def rows(name, vals, fmt, per=12):
        out = [f"static const int16_t {name}[{N}] = {{"]
        for i in range(0, N, per):
            out.append("    " + ", ".join(fmt % v for v in vals[i:i + per]) + ",")
        out.append("};")
        return "\n".join(out)

    body = f"""/* ring_table.h — GENERATED by tools/gen_ring_table.py. Do not edit.
 *
 * The ARP ring's directions as Q12 unit vectors: 64 directions, north = slot 0,
 * clockwise. A ring of n points takes direction a = i*64/n for i in 0..n-1, so
 * this one 256-byte table serves every n (1..64) instead of a table per n.
 *
 * Replaced a hand-typed RING_SIN[64] whose real period was ~70.75 steps: used
 * with a 64-step index it drew a 33%-wobbling not-quite-circle. See the
 * generator for the measurement.
 *
 *   px = cx + (RING_UX[a] * r) >> 12
 *   py = cy + (RING_UY[a] * r) >> 12
 *
 * Q12 is enough for any r this screen has: the worst error at r = 120 is
 * 120 * 0.5 / 4096 = 0.015 px.
 */
#pragma once

{rows("RING_UX", ux, "%6d")}

{rows("RING_UY", uy, "%6d")}
"""
    OUT.write_text(body)
    print(f"wrote {OUT}  ({N} directions, {len(body)} B source, {N * 4} B data)")
    print(f"  quarters exact; worst radius error {worst:.3f} lsb")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
